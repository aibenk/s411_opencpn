#!/usr/bin/env python3
"""Build the OpenCPN "Import plugin" tarball from a built DLL.

Usage:  python packaging/pack.py <path-to-s411_pi.dll>

Produces dist/s411_pi-<version>-msvc-wx32-win32.tar.gz with the layout the
OpenCPN PluginHandler expects: a single top-level directory containing
metadata.xml (parsed after being wrapped in <plugins>...</plugins>, so it must
NOT carry an <?xml ...?> declaration) and plugins/s411_pi.dll.

The metadata is read from packaging/metadata.xml (a real committed file) - it
is never generated by string interpolation, which previously dropped the
quotes around version="1" and produced an unparsable attribute.
"""
import os
import re
import sys
import tarfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
META = os.path.join(HERE, "metadata.xml")


def main():
    if len(sys.argv) < 2:
        sys.exit("usage: pack.py <s411_pi.dll>")
    dll = sys.argv[1]
    if not os.path.isfile(dll):
        sys.exit("DLL not found: " + dll)

    meta = open(META, encoding="utf-8").read()
    if meta.lstrip().startswith("<?xml"):
        sys.exit("metadata.xml must not contain an <?xml ...?> declaration")
    m = re.search(r"<version>([^<]+)</version>", meta)
    if not m:
        sys.exit("no <version> in metadata.xml")
    version = m.group(1).strip()
    # src/s411_version.h is the single source; the metadata must agree
    hdr = open(os.path.join(ROOT, "src", "s411_version.h"), encoding="utf-8").read()
    hv = re.search(r'#define S411_VERSION_STRING "([^"]+)"', hdr)
    if not hv or hv.group(1) != version:
        sys.exit("version mismatch: src/s411_version.h says %s, metadata.xml says %s"
                 % (hv.group(1) if hv else "?", version))
    if ("/v%s/" % version) not in meta or ("-%s-" % version) not in meta:
        sys.exit("metadata.xml tarball-url does not point at release v%s" % version)

    top = "s411_pi-%s" % version
    dist = os.path.join(ROOT, "dist")
    os.makedirs(dist, exist_ok=True)
    out = os.path.join(dist, "%s-msvc-wx32-win32.tar.gz" % top)

    with tarfile.open(out, "w:gz") as t:
        t.add(META, arcname=top + "/metadata.xml")
        t.add(dll, arcname=top + "/plugins/s411_pi.dll")

    # verify the tarball parses exactly the way OpenCPN parses it
    import xml.etree.ElementTree as ET
    with tarfile.open(out) as t:
        data = t.extractfile(top + "/metadata.xml").read().decode("utf-8")
    root = ET.fromstring("<plugins>" + data + "</plugins>")
    name = root.findtext("plugin/name")
    if name != "s411_pi":
        sys.exit("self-check failed: parsed name = %r" % name)
    print("packaged:", out, "(%d bytes, verified)" % os.path.getsize(out))


if __name__ == "__main__":
    main()
